def get_lang() -> str:
    lang = load_settings().get("language", "fr")
    return lang if lang in STRINGS else "fr"


def t(key: str, **kw) -> str:
    s = STRINGS.get(get_lang(), STRINGS["fr"]).get(key)
    if s is None:  # repli : anglais puis français puis la clé
        s = STRINGS["en"].get(key) or STRINGS["fr"].get(key) or key
    return s.format(**kw) if kw else s
